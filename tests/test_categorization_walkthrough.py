"""
tests/test_categorization_walkthrough.py
========================================

How a text line becomes a category, step by step, on concrete inputs (issue #5).

`docs/reference/categorization_rules.md` says what each step does; this file pins it, one line at a time, so a
reader can follow an input through the program and a change that moves any step shows which one. For
every case the model-derived values are INPUTS (FastText's label and confidence, the perplexity), exactly
as `tools/recategorize_from_csv.py` takes them from a CSV, so nothing here loads a model.

What a case asserts, in the order the program takes it
------------------------------------------------------
1. the CPU **pre-filter's route** (`Empty` / `Non-text` / `Process`) and the repaired text;
2. the **stored** language and its score (`remap_lang`), which is what the CSV and the record carry;
3. the **trust score** (`trust_lang_score`: FastText's confidence times the tier of its language), the
   language number the scorer and the structural guards actually read;
4. the **perplexity used** (capped for lines of one or two words, `SHORT_PPL_CAP`);
5. the **rules that fired** and the **reason** that decided, then the **category**;
6. the stored **quality score**, clamped into the band of its category -- `0.80` is where that
   band starts, not what decides between `Clear` and `Noisy`.

Two kinds of case
-----------------
* the rules as designed;
* `known_limit` cases: behaviour that is what the program does today, pinned so that nobody mistakes it
  for a decision and so that fixing it later shows up here. The category semantics are frozen for the S2
  pilot (ocr-postprocess#2); each of these is a measurement to make with `tools/corpus_change.py`
  after it, not a defect to patch in a release.

The `Worked examples` table of the documentation is these cases, generated by `worked_examples_table()`;
`test_the_documentation_carries_the_worked_examples_exactly` keeps the two together.
"""

