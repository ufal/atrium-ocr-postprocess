def test_080_clamps_the_stored_score_and_does_not_decide_clear_from_noisy():
    """`CATEG_NOISY_SCORE_MAX` is read in one place, `categorize_line`'s clamp. Whether a line above the
    Trash band is `Clear` or `Noisy` is decided by its valid-word ratio (0.85) and damaged tokens."""
    # Raw score 0.6447, well below 0.80, yet the line is a candidate for Clear only by its word ratio:
    low_score_clear = walk("Dle zprávy z roku 1932 byla nalezena keramika", "ces_Latn", 0.30, 900)[2]
    assert low_score_clear["valid_word_ratio"] == 1.0
    assert (low_score_clear["categ"], low_score_clear["reason"]) == ("Clear", "clear_threshold")
    # ... and a high raw score with a readability shortfall stays Noisy:
    high_score_noisy = walk("Die Ausgrabung wurde im Jahre 1932 durchgeführt.", "deu_Latn", 0.98, 60)[2]
    assert high_score_noisy["categ"] == "Noisy"
    assert high_score_noisy["quality_score"] == pytest.approx(tu.CATEG_NOISY_SCORE_MAX - 0.0001)


def test_known_limit_czech_doubled_consonants_count_as_repeated_characters():
    """`denní` and `oddělení` are ordinary Czech, but a doubled consonant occurring twice trips
    `detect_repeated_chars` (`REPEATED_DOUBLE_MIN` 2; only `o` and `u` are exempt), so each such word
    carries a weirdness of 0.35. The measurement for after the pilot, not a release fix."""
    assert tu.REPEATED_DOUBLE_MIN == 2 and tu.REPEAT_ALLOWED_CHARS == "oOuU"
    assert tu.detect_repeated_chars("denní") == 1 and tu.detect_repeated_chars("oddělení") == 1
    assert tu.detect_repeated_chars("okolní") == 0
    assert tu.score_word("denní") == pytest.approx(0.35)


