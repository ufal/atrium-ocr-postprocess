def test_pass_3_a_page_of_trash_pulls_its_noisy_lines_down_and_a_clean_page_lifts_trash_up():
    garbage = [_row(1, i, "Trash", f"zz{i} qq", qs=0.3, lang="nld_Latn", lang_score=0.5) for i in range(1, 8)]
    out = _post(garbage + [_row(1, 8, "Noisy", "some words here", qs=0.7, lang="nld_Latn", lang_score=0.5)])
    assert (out.loc[7, "categ"], out.loc[7, "pp_page_context"]) == ("Trash", True)

    clean = [_row(1, i, "Clear", f"Řádek textu {i}", qs=0.92) for i in range(1, 8)]
    out = _post(
        clean
        + [
            _row(1, 8, "Trash", "spoiled line here", qs=0.5),
            _row(1, 9, "Trash", "other spoiled", qs=0.5, lang="nld_Latn"),
            _row(1, 10, "Trash", "very bad", qs=0.3),
        ]
    )
    assert list(out["categ"][7:]) == ["Noisy", "Trash", "Trash"]
    assert out.loc[7, "pp_page_context"] and not out.loc[8, "pp_page_context"]
    assert list(out["quality_score"][7:]) == ["0.5000", "0.5000", "0.3000"], "scores are never recomputed by a pass"


def test_pass_4_a_run_of_suspicious_lines_is_trash_and_empty_or_nontext_lines_do_not_break_it():
    good = [_row(1, i, "Clear", f"dobry radek {i}", lang_score=0.95) for i in (1, 2, 3)]
    run = lambda line, n: _row(1, line, "Noisy", f"noywqued {n} qo", lang_score=0.2, qs=0.7)  # noqa: E731
    out = _post(good + [run(4, 1), run(5, 2), run(6, 3), run(7, 4)])
    assert list(out["categ"][3:]) == ["Trash"] * 4 and all(out["pp_inverted_run"][3:])

    interleaved = _post(
        good + sum([[run(2 * i + 2, i), _row(1, 2 * i + 3, "Non-text", "1998", qs=0.0)] for i in range(1, 5)], [])
    )
    assert [c for c in interleaved["categ"] if c != "Non-text"][3:] == ["Trash"] * 4, "they are left out of the count"

    diacritics = _post([_row(1, i, "Noisy", f"řádek šedý {i}", lang_score=0.2, qs=0.7) for i in range(1, 6)])
    assert set(diacritics["categ"]) == {"Noisy"}, "a Czech diacritic is never suspicious"


# ── the documentation keeps the examples ─────────────────────────────────────────────────────

TABLE_START = "<!-- worked-examples:start -->"
TABLE_END = "<!-- worked-examples:end -->"


def worked_examples_table() -> str:
    """The `Worked examples` table of `docs/reference/categorization_rules.md`, built by running every case.

    Regenerate it into the document (between the two markers) with::

        python -c "from tests.test_categorization_walkthrough import worked_examples_table as t; print(t())"

    The columns are padded to their widest cell, as the Markdown formatter of the repository's editors
    aligns every table, so a regenerated table and a reformatted one are the same text.
    """
    rows = [["Line", "FastText · perplexity", "Rules that fired", "Category", "Reason", "What happens"]]
    for case in CASES:
        if not case.doc:
            continue
        _route, _clean, _sig, fired = walk(case.text, case.lang, case.score, case.ppl)
        text = case.text.replace("|", "\\|")
        rules = ", ".join(f"`{r.removeprefix('rule_')}`" for r in sorted(fired)) or "—"
        language = f"{case.lang.split('_')[0]} {case.score:g} · {case.ppl:g}"
        why = ("**Known limit.** " if case.known_limit else "") + case.why
        rows.append([f"`{text}`", language, rules, case.categ, f"`{case.reason}`", why])
    widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]))]
    lines = ["| " + " | ".join(cell.ljust(w) for cell, w in zip(row, widths, strict=True)) + " |" for row in rows]
    lines.insert(1, "|" + "|".join("-" * (w + 2) for w in widths) + "|")
    return "\n".join(lines)


def _table_cells(table: str) -> list[list[str]]:
    """A Markdown table as its cells: the outer pipes dropped, split on unescaped `|`, each cell stripped and
    a separator cell read as `---`. Padding and separator length are layout, not content."""
    rows = []
    for line in table.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        line = re.sub(r"^\||(?<!\\)\|$", "", line)
        cells = [cell.strip() for cell in re.split(r"(?<!\\)\|", line)]
        rows.append(["---" if re.fullmatch(r":?-+:?", cell) else cell for cell in cells])
    return rows


def test_the_documentation_carries_the_worked_examples_exactly():
    """The table in the documentation IS the cases: the same lines, the same steps, the same verdicts.
    A change to the program that moves one fails the case above; a change to a case fails here until the
    table is regenerated (see `worked_examples_table`). Only the cells are compared: an editor that
    re-aligns the table changes nothing here."""
    text = DOC.read_text(encoding="utf-8")
    assert TABLE_START in text and TABLE_END in text, f"{DOC.name} lost its worked-examples markers"
    documented = _table_cells(text.split(TABLE_START, 1)[1].split(TABLE_END, 1)[0])
    generated = _table_cells(worked_examples_table())
    assert len(documented) == len(generated), (
        f"{DOC.name} has {len(documented)} table rows, the cases give {len(generated)}: regenerate the table"
    )
    for i, (doc_row, case_row) in enumerate(zip(documented, generated, strict=True)):
        assert doc_row == case_row, (
            f"row {i} of the worked examples differs: regenerate the table\n{doc_row}\n{case_row}"
        )
