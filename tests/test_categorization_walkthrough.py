def test_one_and_two_word_lines_get_a_capped_perplexity():
    """`SHORT_PPL_CAP` flattens a one- or two-word line's perplexity before any rule reads it -- below every
    perplexity route's floor -- so no perplexity rule can fire on such a line (gate 6 is its only `Trash`)."""
    assert tu.SHORT_PPL_CAP < tu.HARD_SWEEP_PPL_MIN < tu.PPL_EXTREME_MIN < tu.PPL_GARBAGE_ABSOLUTE
    _r, _c, two, _f = walk("Fundort unbekannt", "deu_Latn", 0.30, 1500)
    _r, _c, three, _f = walk("Der Fundort unbekannt", "deu_Latn", 0.30, 1500)
    assert (two["perplex"], two["perplex_raw"]) == (tu.SHORT_PPL_CAP, 1500.0)
    assert (three["perplex"], three["perplex_raw"]) == (1500.0, 1500.0)


def test_lang_remap_always_off_caps_instead_of_replacing_the_score():
    """`LANG_REMAP_ALWAYS` (default true) sets the stored score of a remapped language to 0.75/0.50 whatever
    FastText said; off, it is `min(score, cap)`. Only the STORED score moves: the trust score, and so the
    category, is read from FastText's own confidence either way."""
    on = walk("Fundort unbekannt", "nld_Latn", 0.30, 1500)[2]
    with tu.override_constants({"LANG_REMAP_ALWAYS": False}):
        off = walk("Fundort unbekannt", "nld_Latn", 0.30, 1500)[2]
        confident = walk("Fundort unbekannt", "nld_Latn", 0.95, 1500)[2]
    assert (on["lang"], on["lang_score"]) == ("ces_Latn", 0.75)
    assert (off["lang"], off["lang_score"]) == ("ces_Latn", 0.30), "a weak guess is left below the cap"
    assert confident["lang_score"] == 0.75, "a confident one is pulled down to it"
    assert (on["trust_lang_score"], off["trust_lang_score"]) == (0.15, 0.15)
    assert on["categ"] == off["categ"] == "Trash"


def test_the_stored_language_number_is_not_what_the_guards_read():
    """An unknown-language line stored at 0.75 reaches the guards as 0.9163 x 0.50 = 0.4582."""
    sig = walk("oueussd", "isl_Latn", 0.9163, 4820)[2]
    assert sig["lang_score"] == 0.75
    assert sig["trust_lang_score"] == pytest.approx(0.4582, abs=1e-4)
    assert sig["lang_score"] == tu.LANG_SCORE_REMAP and sig["trust_lang_score"] <= LC.TRUST_TIER_UNKNOWN


