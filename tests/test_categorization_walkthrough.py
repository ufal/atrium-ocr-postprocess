def test_pass_2_the_window_crosses_a_page_boundary_and_an_empty_line_breaks_it():
    t = lambda page, line: _row(page, line, "Trash", f"t{page}.{line}", qs=0.2)  # noqa: E731
    across = _post([t(1, 9), t(1, 10), _row(2, 1, "Noisy", "island", qs=0.65), t(2, 2), t(2, 3)])
