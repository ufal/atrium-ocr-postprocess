def walk(text: str, lang: str = "ces_Latn", score: float = 0.9, ppl: float = 100.0):
    """The route and, for a line that goes on, every step: `(route, clean, signals, rules_fired)`."""
    route, clean = tu.pre_filter_line(text)
    if route != "Process":
        return route, clean, None, set()
    with tu.rule_fire_capture() as fired:
        sig = LC.score_line(
            text_content=clean,
            original_text=text,
            original_lang=lang,
            original_lang_score=score,
            perplexity=ppl,
            known_lang_bases=KNOWN,
            expected_langs=EXPECTED,
        )
    return route, clean, sig, set(fired)


@dataclass(frozen=True)
class Case:
    """One input and what the program does with it, step by step."""

    id: str
    text: str
    lang: str
    score: float
    ppl: float
    categ: str
    reason: str
    rules: frozenset = field(default_factory=frozenset)  # must have fired (others may have too)
    lang_out: Optional[str] = None  # the stored `lang`; None: not asserted
    score_out: Optional[float] = None  # the stored `lang_score`
    trust: Optional[float] = None  # `trust_lang_score`
    ppl_used: Optional[float] = None  # `perplex`
    clean: Optional[str] = None  # the text after the pre-filter's OCR repairs, when it differs from `text`
    why: str = ""  # one line for the documentation
    known_limit: bool = False
    doc: bool = True


def C(id, text, lang, score, ppl, categ, reason, rules=(), **kw):
    return Case(id, text, lang, score, ppl, categ, reason, frozenset(rules), **kw)


